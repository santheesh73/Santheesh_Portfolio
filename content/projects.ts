export const projects: Project[] = z
  .array(ProjectSchema)
  .superRefine((list, ctx) => {
    const slugs = new Set<string>();
    for (const p of list) {
      if (slugs.has(p.slug)) ctx.addIssue({ code: "custom", message: `duplicate slug ${p.slug}` });
      slugs.add(p.slug);
    }
    for (const f of FEATURED)
      if (!slugs.has(f)) ctx.addIssue({ code: "custom", message: `featured slug ${f} missing` });
  })
  .parse(data);

export const workProjects = projects.filter((p) => p.shelf === "work");
export const labProjects = projects.filter((p) => p.shelf === "lab");
export const featuredProjects = FEATURED.map((s) => projects.find((p) => p.slug === s)!);

export function getProject(slug: string): Project | undefined {
  return projects.find((p) => p.slug === slug);
}

/** Next project in the endless case-study loop (work shelf order). */
export function nextProject(slug: string): Project {
  const list = workProjects;
  const i = list.findIndex((p) => p.slug === slug);
  return list[(i + 1) % list.length]!;
}
